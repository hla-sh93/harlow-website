"""The client's copy: the pages and only the files they use, nothing of the workshop.

Copies every page at the root and every file a page or stylesheet refers to (CSS, JS,
images, video, PDFs, fonts) into a separate folder, keeping their paths. Upload files no
page uses are left out. The stylesheets lose their internal comments (the generator's
header and the source path of each block). Nothing else is changed. Then checks the copy
on its own: every local reference resolves inside it, and no file names the workshop's
tools or any assistant. Finally zips it.

Usage:
    python -u _tools/client_copy.py [destination folder]

Passing looks like:
`N pages and M files (X MB) in <folder> - 0 missing references, 0 workshop mentions`.
"""

import re
import shutil
import sys
import zipfile
from pathlib import Path
from urllib.parse import unquote, urlsplit

from lxml import html as lxml_html

from common import ROOT

ATTRS = ("href", "src", "poster", "data-thumbnail", "preloader-image-url")
MENTIONS = re.compile(r"claude|anthropic|openai|chatgpt|copilot|gemini|ai-generated|_tools|"
                      r"agents\.md|_capture|_source|_inventory", re.I)
CSS_INTERNAL = re.compile(r"^/\* (?:[\w/.-]+: generated by .*?|from .*?) \*/\n", re.M)


def is_local(ref):
    return ref and not re.match(r"^(https?:|mailto:|tel:|javascript:|data:|#)", ref)


def page_refs(path):
    doc = lxml_html.fromstring(path.read_text(encoding="utf-8"))
    for el in doc.iter():
        if not isinstance(el.tag, str):
            continue
        for a in ATTRS:
            if el.get(a):
                yield el.get(a)
        if el.get("srcset"):
            for cand in re.split(r",[ \t\n\r\f]+", el.get("srcset").strip()):
                yield re.split(r"[ \t\n\r\f]+", cand.strip())[0]
        if el.get("style"):
            yield from re.findall(r"url\(\s*['\"]?([^'\")]+)", el.get("style"))


def css_refs(text):
    return re.findall(r"url\(\s*['\"]?([^'\")]+)", text)


def collect():
    """Every file the site needs, relative to the project root."""
    files = set()
    for page in sorted(ROOT.glob("*.html")):
        files.add(page.name)
        for ref in page_refs(page):
            if is_local(ref):
                p = unquote(urlsplit(ref).path)
                if p.endswith(".html"):
                    continue
                files.add(p)
    for css in [f for f in list(files) if f.endswith(".css")]:
        base = (ROOT / css).parent
        for ref in css_refs((ROOT / css).read_text(encoding="utf-8")):
            if is_local(ref):
                target = (base / unquote(urlsplit(ref).path)).resolve()
                files.add(target.relative_to(ROOT.resolve()).as_posix())
    return sorted(files)


def verify(dest):
    """References inside the copy, checked against the copy alone."""
    missing, mentions = [], []
    for f in dest.rglob("*"):
        if not f.is_file():
            continue
        if f.suffix in (".html", ".css", ".js") and MENTIONS.search(f.read_text(encoding="utf-8")):
            mentions.append(f.relative_to(dest).as_posix())
        if f.suffix == ".html":
            for ref in page_refs(f):
                if is_local(ref) and not (dest / unquote(urlsplit(ref).path)).exists():
                    missing.append(f"{f.name}: {ref}")
        elif f.suffix == ".css":
            for ref in css_refs(f.read_text(encoding="utf-8")):
                if is_local(ref) and not (f.parent / unquote(urlsplit(ref).path)).exists():
                    missing.append(f"{f.relative_to(dest).as_posix()}: {ref}")
    return missing, mentions


def main(dest):
    if dest.exists():
        shutil.rmtree(dest)
    files = collect()
    size = 0
    for rel in files:
        src, out = ROOT / rel, dest / rel
        if not src.exists():
            print("  NOT FOUND in the project:", rel)
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        if src.suffix == ".css":
            out.write_text(CSS_INTERNAL.sub("", src.read_text(encoding="utf-8")).lstrip("\n"),
                           encoding="utf-8")
        else:
            shutil.copyfile(src, out)
        size += out.stat().st_size
    missing, mentions = verify(dest)
    for m in missing[:20]:
        print("  MISSING", m)
    for m in mentions[:20]:
        print("  MENTION", m)
    pages = len(list(dest.glob("*.html")))
    zip_path = dest.with_suffix(".zip")
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(dest.rglob("*")):
            if f.is_file():
                z.write(f, Path(dest.name) / f.relative_to(dest))
    print(f"{pages} pages and {len(files) - pages} files ({size / 1e6:.1f} MB) in {dest} - "
          f"{len(missing)} missing references, {len(mentions)} workshop mentions")
    print(f"zip: {zip_path} ({zip_path.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "harlow-website"
    main(target)
